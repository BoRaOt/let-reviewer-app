#!/usr/bin/env python3
"""Write site/sw.js: precache every app file under a cache name derived from their content hash,
so any change to code or data produces a new cache and the app offers a reload.
Run after changing anything in site/:  python3 scripts/build_sw.py"""
import hashlib, os

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "site")
files = []
for dp, _, fns in os.walk(ROOT):
    for fn in sorted(fns):
        rel = os.path.relpath(os.path.join(dp, fn), ROOT).replace(os.sep, "/")
        if rel in ("sw.js",) or fn.startswith("."):
            continue
        files.append(rel)
files.sort()
h = hashlib.sha256()
for rel in files:
    h.update(rel.encode())
    h.update(open(os.path.join(ROOT, rel), "rb").read())
version = h.hexdigest()[:12]
assets = ["./"] + files
sw = f"""/* Generated by scripts/build_sw.py — do not edit by hand. */
'use strict';
var CACHE = 'let-study-{version}';
var ASSETS = {assets!r};

self.addEventListener('install', function (e) {{
  e.waitUntil(caches.open(CACHE).then(function (c) {{ return c.addAll(ASSETS); }}));
}});
self.addEventListener('activate', function (e) {{
  e.waitUntil(caches.keys().then(function (keys) {{
    return Promise.all(keys.filter(function (k) {{ return k.indexOf('let-study-') === 0 && k !== CACHE; }}).map(function (k) {{ return caches.delete(k); }}));
  }}).then(function () {{ return self.clients.claim(); }}));
}});
self.addEventListener('message', function (e) {{ if (e.data === 'skipWaiting') self.skipWaiting(); }});
self.addEventListener('fetch', function (e) {{
  if (e.request.method !== 'GET') return;
  var url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(function (hit) {{
    if (hit) return hit;
    return fetch(e.request).then(function (res) {{
      if (res.ok && res.type === 'basic') {{ var copy = res.clone(); caches.open(CACHE).then(function (c) {{ c.put(e.request, copy); }}); }}
      return res;
    }}).catch(function () {{
      if (e.request.mode === 'navigate') return caches.match('./index.html');
      return Response.error();
    }});
  }}));
}});
"""
open(os.path.join(ROOT, "sw.js"), "w").write(sw.replace("'", "'"))
print("sw.js", version, len(assets), "assets")
